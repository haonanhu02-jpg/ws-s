CREATE TABLE dormitory_bed (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 building_name VARCHAR(100) NOT NULL,
 room_number VARCHAR(50) NOT NULL,
 bed_code VARCHAR(50) NOT NULL UNIQUE,
 enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE dormitory_record (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 visit_id VARCHAR(40) NOT NULL UNIQUE,
 visitor_name VARCHAR(100) NOT NULL, mobile VARCHAR(30) NOT NULL,
 identity_card_number VARCHAR(255), host_name VARCHAR(100) NOT NULL,
 host_department VARCHAR(150) NOT NULL, visit_reason VARCHAR(500) NOT NULL,
 accommodation_required BOOLEAN NOT NULL, has_vehicle BOOLEAN NOT NULL,
 plate_number VARCHAR(30), vehicle_entering_factory BOOLEAN NOT NULL,
 accommodation_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
 bed_id BIGINT UNIQUE REFERENCES dormitory_bed(id), created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE dormitory_processed_event(event_id VARCHAR(50) PRIMARY KEY,processed_at TIMESTAMP WITH TIME ZONE NOT NULL);
CREATE TABLE bed_change_audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,visit_id VARCHAR(40) NOT NULL,old_bed_id BIGINT,new_bed_id BIGINT NOT NULL,operator_name VARCHAR(100) NOT NULL,changed_at TIMESTAMP WITH TIME ZONE NOT NULL);
