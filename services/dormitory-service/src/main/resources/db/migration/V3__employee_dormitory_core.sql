CREATE TABLE dorm_building (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE,
 region_name VARCHAR(100) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 display_order INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dorm_room (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 building_id BIGINT NOT NULL REFERENCES dorm_building(id),
 room_no VARCHAR(50) NOT NULL,
 floor_no INTEGER NOT NULL,
 facing VARCHAR(20), room_type VARCHAR(30) NOT NULL,
 livable BOOLEAN NOT NULL DEFAULT TRUE,
 cleaning_required BOOLEAN NOT NULL DEFAULT FALSE,
 grid_col INTEGER, grid_row INTEGER, grid_col_span INTEGER, grid_row_span INTEGER,
 display_order INTEGER NOT NULL DEFAULT 0,
 special_note VARCHAR(500), enabled BOOLEAN NOT NULL DEFAULT TRUE,
 version BIGINT NOT NULL DEFAULT 0,
 UNIQUE(building_id, room_no)
);

CREATE TABLE dorm_bed (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 room_id BIGINT NOT NULL REFERENCES dorm_room(id),
 label VARCHAR(50) NOT NULL,
 bed_code VARCHAR(100) NOT NULL UNIQUE,
 three_piece VARCHAR(50), enabled BOOLEAN NOT NULL DEFAULT TRUE,
 version BIGINT NOT NULL DEFAULT 0,
 UNIQUE(room_id, label)
);

CREATE TABLE dorm_person (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, center_name VARCHAR(150), department VARCHAR(150) NOT NULL,
 gender VARCHAR(10) NOT NULL, category VARCHAR(100) NOT NULL,
 position_name VARCHAR(100), rank_name VARCHAR(100),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_dorm_person_name ON dorm_person(name);

CREATE TABLE dorm_stay (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 person_id BIGINT NOT NULL REFERENCES dorm_person(id),
 bed_id BIGINT NOT NULL REFERENCES dorm_bed(id),
 status VARCHAR(30) NOT NULL,
 application_code VARCHAR(100), liaison VARCHAR(100), bed_type VARCHAR(50) NOT NULL,
 cost_cut BOOLEAN NOT NULL, promise_signed BOOLEAN,
 move_in_water DECIMAL(14,2), move_in_electric DECIMAL(14,2),
 move_out_water DECIMAL(14,2), move_out_electric DECIMAL(14,2),
 planned_move_in DATE NOT NULL, planned_move_out DATE,
 checked_in_at TIMESTAMP WITH TIME ZONE, checked_out_at TIMESTAMP WITH TIME ZONE,
 special_note VARCHAR(500), remark VARCHAR(1000),
 operator_name VARCHAR(100) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_dorm_stay_status ON dorm_stay(status);
CREATE INDEX idx_dorm_stay_bed ON dorm_stay(bed_id);

CREATE TABLE dorm_stay_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 stay_id BIGINT NOT NULL REFERENCES dorm_stay(id),
 action VARCHAR(40) NOT NULL, old_bed_id BIGINT, new_bed_id BIGINT,
 before_status VARCHAR(30), after_status VARCHAR(30),
 operator_name VARCHAR(100) NOT NULL, reason VARCHAR(500),
 operated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
